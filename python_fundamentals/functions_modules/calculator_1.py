#!/usr/bin/env python3
"""Simple calculator functions."""


def add(a, b):
    """Return a plus b."""
    return a + b


def sub(a, b):
    """Return a minus b."""
    return a - b


def mul(a, b):
    """Return a multiplied by b."""
    return a * b


def div(a, b):
    """Return a divided by b."""
    return a / b
